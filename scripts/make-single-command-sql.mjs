/**
 * Wrap the bootstrap schema into ONE command.
 *
 * The plain multi-statement file is rejected by any client that uses
 * PostgreSQL's extended query protocol: "cannot insert multiple commands into a
 * prepared statement". That is not a quirk of one tool — it is the protocol
 * rule, and it bites the Neon SQL editor, the Neon serverless driver, and any
 * `client.query({name, text})` in node-pg. Reproduced before this was written.
 *
 * A `DO` block is a single command whose body is PL/pgSQL, and plain DDL runs
 * inside PL/pgSQL unchanged. So the entire schema goes through as one prepared
 * statement with no edits to the SQL itself.
 *
 * The one thing that cannot survive verbatim: PL/pgSQL has no `DO` statement of
 * its own, so the two legacy-repair blocks in the source are INLINED — their
 * bodies spliced in and their DECLAREs hoisted to the wrapper. Their behaviour
 * is unchanged, which is what the twice-run verification checks.
 *
 * Usage: node scripts/make-single-command-sql.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = 'docs/schema-bootstrap.sql'
const OUT = 'docs/schema-bootstrap-single.sql'

let sql = readFileSync(SRC, 'utf8')

// Match `DO $$ ... END $$;`. Non-greedy, so the two blocks do not merge.
const DO_BLOCK = /DO \$\$\n([\s\S]*?)\nEND \$\$;/g
const blocks = [...sql.matchAll(DO_BLOCK)]
if (blocks.length !== 2) {
  // Refuse rather than emit something that looks right. A zero-match would
  // otherwise produce a file with DO blocks still nested inside a DO block,
  // which PL/pgSQL rejects — and it would only be discovered at run time,
  // against the user's real database. This guard has already earned its keep.
  throw new Error(`expected 2 DO blocks in ${SRC}, found ${blocks.length}`)
}

for (const block of blocks) {
  let body = block[1]
  body = body.replace(/^DECLARE[\s\S]*?(?=BEGIN)/, '') // hoisted to the wrapper
  body = body.replace(/^BEGIN\n/, '')
  sql = sql.replace(block[0], body.trim())
}

const out = `-- Handsel schema bootstrap — SINGLE-COMMAND form.
--
-- Use this one if the multi-statement file gives you
--   "cannot insert multiple commands into a prepared statement"
-- That is PostgreSQL's extended query protocol refusing more than one command
-- per prepared statement, and it is the rule rather than a quirk of one client.
--
-- A DO block IS one command, so the whole schema goes through as a single
-- prepared statement. Same tables, same idempotence — verified by running this
-- exact file twice, through the prepared-statement path, against a clean
-- PostgreSQL 16.
--
-- The two legacy-repair DO blocks from the source file are inlined here, and
-- their DECLAREs hoisted, because PL/pgSQL has no DO statement of its own.
--
-- Generated by scripts/make-single-command-sql.mjs — edit that, or
-- docs/schema-bootstrap.sql, never this.

DO $bootstrap$
DECLARE
  t text;
  n bigint;
BEGIN
${sql
  .split('\n')
  .map((line) => (line.length ? '  ' + line : line))
  .join('\n')}
END
$bootstrap$;
`

writeFileSync(OUT, out)
console.log(`wrote ${OUT} — ${out.length} bytes`)
